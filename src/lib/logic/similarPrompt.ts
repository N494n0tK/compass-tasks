/**
 * Compass — 「苦手な問題の類題を作る」プロンプト（docs/daily-mission/plan.md §4.4）
 *
 * このアプリの AI 連携は API を叩かず、**プロンプトをコピーして外部 AI に貼る**のが正典
 * （docs/notebook/spec.md §1 のワークフロー手順 2）。ここもその流儀のまま、問題抽出の画面から
 * 「いま苦手な問題の類題を作らせるプロンプト」をワンタップで持ち出せるようにする。
 *
 * 取り込み用のプロンプト（`components/parts/NotePrompts.ts`）との一番の違いは
 * **JSON を要求しないこと**。類題は紙やノートで解く練習材料であって、アプリへ戻す対象ではない
 * （戻したところで、自分の授業ノートに紐づかない問題がカードとして増えるだけになる）。
 * 取り込まないと決めたので、この 2 つが要らなくなる:
 *
 *  - **バックスラッシュを 2 個重ねる指示**。あれは JSON 文字列にするための約束事だった。
 *    ノートの `q` / `a` は取り込みのときに JSON から解けた状態＝バックスラッシュ 1 個で
 *    保存されている。それをそのまま本文へ貼るので、プロンプト側も 1 個の流儀で通す。
 *  - **スキーマと出力前の自己チェック**。普通の文章で返してもらえばよいぶん、短く済む。
 *
 * React も store も import しない純関数（テストしやすさのため）。
 */

import { lastOf, type DrillItem } from './noteExtract';

/**
 * 1 回のプロンプトに載せる問題数の上限。
 *
 * 5 問にしたのは、1 問につき類題 2 問＝合計 10 問が、貼ったその日に紙で解ける上限だから。
 * 増やすほど 1 問あたりの作りが雑になり（AI の出力長は問題数に比例して伸びない）、
 * 結局どれも解かずに終わる。足りなければ絞り込みを変えてもう一度コピーすればよい。
 */
export const SIMILAR_TARGET_MAX = 5;

/**
 * 類題を作らせる対象を選ぶ。`items` は**呼び出し側でフィルタ済み**のもの
 * （＝画面に出ている並び）を渡す。
 *
 *  - **一度でも解いた問題だけ**。まだ解いていない問題の「類題」は意味が薄い ―― その問題自体を
 *    まだ解いていないのだから、まずそれを解けばいい。演習（`note.exercise`）は記録を持てない
 *    ので、この条件だけで自然に外れる（演習向けの分岐をわざわざ書かない）。
 *  - 優先順は **△不安 → ○まあまあ**。◎ばっちりだけの問題は対象にしない（できている問題の
 *    練習を増やしても、苦手は埋まらない）。
 *  - 同順位のときは**渡された並びのまま**。画面の並びが保たれるので、「上から順に拾われた」
 *    と読めて、なぜこの問題が選ばれたのかが目で追える。
 */
export function pickSimilarTargets(
  items: readonly DrillItem[],
  max: number = SIMILAR_TARGET_MAX,
): DrillItem[] {
  const keyed: { it: DrillItem; i: number; rank: number }[] = [];
  items.forEach((it, i) => {
    const last = lastOf(it);
    if (!last) return; // 未着手（演習もここで落ちる）
    if (last.grade === 'high') return; // ◎だけの問題に類題は要らない
    keyed.push({ it, i, rank: last.grade === 'low' ? 0 : 1 });
  });
  // 同点は入力順のまま（`noteExtract.sortDrillItems` と同じ、添字を持ち回る安定ソート）
  keyed.sort((a, b) => (a.rank !== b.rank ? a.rank - b.rank : a.i - b.i));
  return keyed.slice(0, Math.max(0, max)).map((k) => k.it);
}

/**
 * 外部 AI に貼るプロンプトを組み立てる。対象が空なら空文字
 * （UI 側はそのときボタンを押せなくしてあるので、ここへは来ない）。
 */
export function buildSimilarPrompt(targets: readonly DrillItem[]): string {
  if (!targets.length) return '';
  const body = targets
    .map((it, i) =>
      [
        '## 問題' + (i + 1) + ' ── ' + it.note.subject + ' ／ ' + it.note.unit,
        '【元の問題】',
        it.q.trim(),
        '【模範解答】',
        it.a.trim() || '（解答が書かれていません。まず正しい解答を作ってから類題へ進んでください）',
      ].join('\n'),
    )
    .join('\n\n');
  // 前半は空行で終わり、後半は空行を挟んで続く（貼ったときに見出しが埋もれないように）
  const head = SIMILAR_HEAD.replace(/__N__/g, String(targets.length));
  const tail = SIMILAR_TAIL.replace(/__M__/g, String(targets.length * 2));
  return head + body + '\n\n' + tail;
}

/**
 * プロンプトの前半。**模範解答も一緒に渡す**のがここの肝。
 * 問題文だけ見せると AI は問題の意図を取り違えた類題を作る（同じ見た目で別の解法の問題に
 * なる）。解答まで見せたうえで「数値や設定を変えたもの」を頼むほうが、出来が安定する。
 *
 * `String.raw` は使わない ―― この文にバックスラッシュを入れないため（LaTeX の書き方は
 * 「$ で囲む」とだけ言えば足り、記号の見本を出す必要がない）。
 */
const SIMILAR_HEAD = `あなたは高校生の家庭教師です。
下に挙げる__N__問がいま苦手なので、同じ考え方で解ける**類題**を作って練習させてください。

# 苦手な問題（__N__問）
問題ごとに、元の問題文と模範解答を載せます。**解答まで読んだうえで**類題を作ってください
（何をどう問われている問題なのかは、解答を見ないと決まらないため）。

`;

/** プロンプトの後半。要求と書き方。`__M__` は作らせる類題の合計問数 */
const SIMILAR_TAIL = `# 作ってほしいもの
- 上の1問につき**類題を2問**ずつ（合計__M__問）。
- 数値・設定・場面を変える。**元の問題の焼き直しにしない。** 使う考え方は同じにする。
- 難易度は元の問題と**同等〜やや易しめ**。ひねりを足して難しくしない。
- 1問ごとに「問題文 → 解答 → 解説（2〜3行）」を書く。解説は「どこに気づけば解けるか」を書く。
- 最後に「元の問題 → 作った類題」の対応を一覧（表）にする。

# 書き方
- 数式は $...$（行内）/ $$...$$（別行）の LaTeX で書く。JSONではないので、バックスラッシュは1個でよい。
- **出力は普通の文章で。** JSONにはしない（アプリには取り込まず、そのまま紙に解くため）。
- 教科・単元は上の見出しのものに合わせる。その単元で使わない道具を持ち出さない。
`;

/** ボタンの文言 */
export const SIMILAR_COPY_LABEL = '類題プロンプトをコピー';

/**
 * ボタンに添える説明。押せないときは**そのまま理由になる**ようにしてある
 * （`title` と補足文言で同じ文を使う。2 か所で言い回しがずれないように 1 本にした）。
 */
export function similarCopyHint(count: number): string {
  return count
    ? '表示中の問題から苦手な' + count + '問を選び、外部AIに貼るプロンプトを作ります'
    : '対象がありません(一度解いて △不安 / ○まあまあ を付けた問題が対象です)';
}

/** コピーできたときのトースト */
export function similarCopyToast(count: number): string {
  return '類題プロンプトをコピーしました(' + count + '問ぶん)。ChatGPTに貼ってください';
}

/** コピーできなかったときのトースト（取り込みモーダルと同じ言い方） */
export const SIMILAR_COPY_FAIL_TOAST = 'コピーできませんでした(手動で選択してください)';
